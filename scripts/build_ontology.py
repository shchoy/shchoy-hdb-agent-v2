def annotations(element: Any) -> dict[str, Any]:
    return {tag: a["value"] if isinstance(a, dict) else a.value for tag, a in as_dict(element.annotations).items()}


@dataclass
class Edge:
    type: str
    slot: str
    domain: str
    range: str
    cardinality: str
    extracted: bool
    description: str | None
    domain_labels: list[str]
    range_labels: list[str]


class Ontology:
    def __init__(self, schema: Path) -> None:
        self.schema = schema
        self.view = SchemaView(str(schema))
        self.nodes = [c for c in self.view.all_classes() if annotations(self.view.get_class(c)).get("node")]
        self.vocabulary_slots = {
            slot: f"plg:{meta['vocabulary']}"
            for slot in self.view.all_slots()
            if "vocabulary" in (meta := annotations(self.view.get_slot(slot)))
        }

    def labels(self, cls: str) -> list[str]:
        return [c for c in self.descendants(cls) if c in self.nodes]

    def descendants(self, cls: str) -> list[str]:
        return list(self.view.class_descendants(cls, reflexive=True))

    def edges(self) -> list[Edge]:
        edges = []
        for cls in self.view.all_classes():
            for slot in self.view.get_class(cls).slots:
                induced = self.view.induced_slot(slot, cls)
                meta = annotations(induced)
                if "edge" not in meta:
                    continue
                low = "1" if induced.required else "0"
                high = "*" if induced.multivalued else "1"
                edges.append(Edge(
                    type=meta["edge"],
                    slot=slot,
                    domain=cls,
                    range=induced.range,
                    cardinality=low if low == high else f"{low}..{high}",
                    extracted=bool(meta.get("extracted", False)),
                    description=induced.description,
                    domain_labels=self.labels(cls),
                    range_labels=self.labels(induced.range),
                ))
        return edges

    def models(self) -> tuple[str, types.ModuleType]:
        """The generated Pydantic models: source to write, and the module loaded from it to validate with."""
        source = f"# {HEADER}\n" + PydanticGenerator(str(self.schema)).serialize()
        module = types.ModuleType("_plg_ontology_models")
        sys.modules[module.__name__] = module  # Pydantic resolves forward references through sys.modules.
        exec(compile(source, "models.py", "exec"), module.__dict__)
        return source, module


@dataclass
class Scheme:
    scheme: str
    concept_class: str
    title: str
    concepts: list[Any] = field(default_factory=list)


@dataclass
class Validation:
    """Collects every problem, and the concept IDs and codes that references must resolve to."""

    onto: Ontology
    errors: list[str] = field(default_factory=list)
    concept_classes: dict[str, str] = field(default_factory=dict)
    notations: dict[str, set[str]] = field(default_factory=dict)

    def load(self, path: Path, models: types.ModuleType) -> Scheme:
        """A vocabulary or glossary file, validated against the generated model of its concept class."""
        data = yaml.safe_load(path.read_text())
        scheme = Scheme(data["scheme"], data["concept_class"], data["title"])
        cls = getattr(models, scheme.concept_class, None)
        if cls is None or not issubclass(cls, models.Concept):
            self.errors.append(f"{path.name}: concept_class {scheme.concept_class} is not a Concept class")
            return scheme
        for raw in data["concepts"]:
            try:
                scheme.concepts.append(cls.model_validate({"in_scheme": scheme.scheme, **raw}))
            except ValidationError as e:
                self.errors.append(f"{path.name}: {raw.get('id')}: {e}")
        self.notations[scheme.scheme] = {c.notation for c in scheme.concepts if c.notation}
        for c in scheme.concepts:
            if c.id in self.concept_classes:
                self.errors.append(f"{scheme.scheme}: duplicate concept id {c.id}")
            self.concept_classes[c.id] = scheme.concept_class
        return scheme

    def check_references(self, cls: str, obj: dict[str, Any], where: str) -> None:
        """Every reference names a concept of the right class; every vocabulary value is in its scheme."""
        view = self.onto.view
        for slot, value in obj.items():
            if slot == "id" or slot not in view.class_slots(cls):
                continue
            target = view.induced_slot(slot, cls).range
            for v in value if isinstance(value, list) else [value]:
                if slot in self.onto.vocabulary_slots:
                    scheme = self.onto.vocabulary_slots[slot]
                    if v not in self.notations.get(scheme, set()):
                        self.errors.append(f"{where}: {slot} {v!r} is not in {scheme}")
                elif isinstance(v, dict):
                    self.check_references(target, v, where)
                elif target in self.onto.descendants("Concept"):
                    # Vocabulary references must resolve now; references to records are checked at graph build.
                    if self.concept_classes.get(v) not in self.onto.descendants(target):
                        self.errors.append(f"{where}: {slot} {v!r} is not a {target}")


def extraction_schema(edge_type: str, edges: list[Edge]) -> dict[str, Any]:
    domains = sorted({label for e in edges for label in e.domain_labels})
    ranges = sorted({label for e in edges for label in e.range_labels})
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$comment": HEADER,
        "title": f"{edge_type} edges",
        "description": edges[0].description,
        "type": "object",
        "additionalProperties": False,
        "required": ["edges"],
        "properties": {
            "edges": {
                "type": "array",
                "items": {
                    "type": "object",
                    "additionalProperties": False,
                    "required": ["type", "source_id", "source_label", "target_id", "target_label",
                                 "evidence_chunk_id", "evidence_quote"],
                    "properties": {
                        "type": {"const": edge_type},
                        "source_id": {"type": "string", "description": "ID of the source node."},
                        "source_label": {"enum": domains},
                        "target_id": {"type": "string", "description": "ID of the target node."},
                        "target_label": {"enum": ranges},
                        "evidence_chunk_id": {"type": "string", "description": "Chunk the relation is read from."},
                        "evidence_quote": {
                            "type": "string",
                            "description": "Verbatim span of the chunk that states the relation.",
                        },
                        "scope": {
                            "type": "string",
                            "description": "Units or cases the relation is limited to, if any (e.g. NC units only).",
                        },
                    },
                },
            }
        },
    }


def vocab_index(vocab: list[Scheme], glossary: Scheme) -> dict[str, Any]:
    """Concepts by scheme, and every normalised label/synonym -> the concepts it names."""
    labels: dict[str, list[dict[str, Any]]] = {}

    def add_labels(ref: dict[str, Any], names: list[str]) -> None:
        for name in filter(None, names):
            refs = labels.setdefault(normalise(name), [])
            if ref not in refs:
                refs.append(ref)

    schemes = {s.scheme: [c.model_dump(mode="json", exclude_none=True) for c in s.concepts] for s in vocab}
    for scheme, concepts in schemes.items():
        for c in concepts:
            ref = {"id": c["id"], "scheme": scheme, "pref_label": c["pref_label"], "notation": c.get("notation")}
            add_labels(ref, [c["pref_label"], c.get("notation", ""), *c.get("alt_labels", [])])
    for t in glossary.concepts:
        ref = {"id": t.concept, "scheme": glossary.scheme, "pref_label": t.pref_label, "notation": None}
        add_labels(ref, [t.pref_label, *(t.alt_labels or [])])
    return {"$comment": HEADER, "schemes": schemes, "labels": dict(sorted(labels.items()))}


def ontology_card(onto: Ontology, edges: list[Edge], vocab: list[Scheme], glossary: Scheme) -> str:
    lines = [f"<!-- {HEADER} -->", f"# PLG ontology card (v{onto.view.schema.version})", "", "## Node labels"]
    for label in onto.nodes:
        description = onto.view.get_class(label).description
        lines.append(f"- {label}" + (f": {description}" if description else ""))
    lines += ["", "## Relations (domain -TYPE-> range [cardinality]; * = extracted from documents)"]
    for e in edges:
        lines.append(f"- {e.domain} -{e.type}-> {e.range} [{e.cardinality}]" + ("*" if e.extracted else ""))
    lines += ["", "## Vocabularies (code: label)"]
    for s in vocab:
        terms = "; ".join(
            c.pref_label if c.notation in (None, c.pref_label) else f"{c.notation}: {c.pref_label}"
            for c in s.concepts
        )
        lines.append(f"- {s.scheme.removeprefix('plg:')}: {terms}")
    lines += ["", "## Glossary (current definitions; cite the ID and version)"]
    for t in glossary.concepts:
        if t.status == "current":
            value = f" [{t.value}]" if t.value else ""
            lines.append(f"- {t.id} {t.pref_label} (from {t.effective_from}){value}: {t.definition}")
    return "\n".join(lines) + "\n"


def build(source: Path, out: Path) -> int:
    onto = Ontology(source / "plg.yaml")
    models_source, models = onto.models()

    check = Validation(onto)
    vocab = [check.load(path, models) for path in sorted((source / "vocab").glob("*.yaml"))]
    glossary = check.load(source / "glossary.yaml", models)
    for scheme in set(onto.vocabulary_slots.values()) - {s.scheme for s in vocab}:
        check.errors.append(f"ontology: vocabulary {scheme} has no file under {source / 'vocab'}")
    for s in vocab:
        for c in s.concepts:
            check.check_references(s.concept_class, c.model_dump(mode="json", exclude_none=True), f"{s.scheme} {c.id}")
    check.errors += [f"glossary: {e}" for e in supersedes_errors(glossary.concepts)]
    staff = load_personas(Settings.from_env().records_db)
    check.errors += [
        f"glossary: {t.id}: owner {t.owned_by} is not a staff ID" for t in glossary.concepts if t.owned_by not in staff
    ]
    layer = parse_semantic_layer(yaml.safe_load((source / "semantic.yaml").read_text()))
    check.errors += semantic_errors(layer, {t.id for t in glossary.concepts}, Warehouse(Settings.from_env().records_db))
    if check.errors:
        print("make ontology: invalid ontology", *check.errors, sep="\n  ", file=sys.stderr)
        return 1

    def write(name: str, content: str | dict[str, Any]) -> None:
        path = out / name
        path.parent.mkdir(parents=True, exist_ok=True)
        text = content if isinstance(content, str) else json.dumps(content, indent=2, ensure_ascii=False) + "\n"
        path.write_text(text)

    edges = onto.edges()
    write("models.py", models_source)
    tool_schema = json.loads(JsonSchemaGenerator(str(onto.schema), mergeimports=True).serialize())
    write("plg.schema.json", {"$comment": HEADER, **tool_schema})
    for edge_type in sorted({e.type for e in edges if e.extracted}):
        matching = [e for e in edges if e.type == edge_type and e.extracted]
        write(f"extraction/{edge_type.lower()}.json", extraction_schema(edge_type, matching))
    write("allow_list.json", {"$comment": HEADER, "node_labels": onto.nodes, "edges": [asdict(e) for e in edges]})
    write("vocab_index.json", vocab_index(vocab, glossary))
    write("glossary_index.json", {
        "$comment": HEADER,
        "terms": [t.model_dump(mode="json", exclude_none=True) for t in glossary.concepts],
    })
    write("semantic_layer.json", {"$comment": HEADER, **layer.model_dump(mode="json")})
    write("ontology_card.md", ontology_card(onto, edges, vocab, glossary))

    print(f"make ontology: {len(onto.nodes)} node labels, {len({e.type for e in edges})} edge types, "
          f"{sum(len(s.concepts) for s in vocab)} concepts in {len(vocab)} vocabularies, "
          f"{len(glossary.concepts)} glossary versions, {len(layer.bindings)} SQL bindings -> {out}")
    return 0


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--source", type=Path, default=ROOT / "ontology")
    parser.add_argument("--out", type=Path, default=GENERATED)
    args = parser.parse_args()
    sys.exit(build(args.source, args.out))
