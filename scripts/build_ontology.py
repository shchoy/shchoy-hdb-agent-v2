"""`make ontology`: generate every ontology artefact from ontology/ into src/plg/ontology/generated/.

Sources: ontology/plg.yaml (LinkML classes and relations), ontology/vocab/*.yaml (SKOS-style vocabularies)
and ontology/glossary.yaml (versioned GlossaryTerms). Outputs: Pydantic models, JSON Schema for tool I/O,
edge extraction schemas, the graph allow-list, the vocabulary (synonym) index, the glossary index and a
compact ontology card for system prompts.

Everything is validated before anything is written: if the vocabularies or glossary don't fit the ontology,
or a `supersedes` chain is broken, it lists every problem, exits 1 and leaves the generated files untouched.
"""

